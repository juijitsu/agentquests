"""Уровень 04 · новичок.

    solve([1200, 900, 1450]) -> 1200
"""


def solve(quotes: list[int]) -> int:
    # TODO: середина списка — это не середина по деньгам. Ставки приходят
    #       в том порядке, в каком их прислали перевозчики, и середина такого
    #       списка случайна.
    #       Сперва выстройте ставки по возрастанию: in_order = sorted(quotes)
    #       Номер середины считайте по нему:        middle = len(in_order) // 2
    #       И берите элемент из него же:            in_order[middle]
    middle = len(quotes) // 2
    return quotes[middle]
