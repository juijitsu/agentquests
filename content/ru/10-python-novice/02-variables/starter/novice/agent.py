"""Уровень 02 · новичок.

    solve("1450") -> "1450 + 60 = 1510"
"""


def solve(miles: str) -> str:
    # TODO: miles — текст, поэтому miles + "60" склеивает цифры, а не
    #       складывает их: "1450" + "60" даёт "145060", а 1450 + 60 даёт 1510.
    #       Сперва сделайте из текста число:       loaded = int(miles)
    #       Прибавляйте к числу, а не к тексту:    total = loaded + 60
    #       Чтобы вернуть число в строку:          str(total)
    total = miles + "60"
    return miles + " + 60 = " + total
