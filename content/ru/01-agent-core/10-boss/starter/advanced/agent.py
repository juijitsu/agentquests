"""Уровень 10 · продвинутый.

Смена обязана закрыться так, чтобы выполнялись четыре условия сразу:

    очередь растёт на ходу        — снимок устареет
    человека беспокоят по делу    — его внимание кончается
    согласование переживает крах  — процесс умрёт на середине
    цикл конечен                  — условие выхода снаружи

Ниже — рабочий диспетчер, нарушающий первые три. Четвёртое он соблюдает
случайно: обход снимка конечен сам собой. Живое чтение это свойство отнимет.
"""

from scenario import APPROVED, EMPTY, Model, TOOLS, run_tool

MAX_STEPS = 12


def run() -> tuple[str, int]:
    model = Model()
    step = 0

    for action in run_tool("pending", {}).split(" | "):
        step += 1
        run_tool("ask", {"name": action})
        run_tool("handle", {"name": action})

    return model.close(), step
